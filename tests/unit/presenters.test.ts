import {
  presentAudit,
  presentBuyer,
  presentConversation,
  presentCrop,
  presentDelivery,
  presentDispute,
  presentDocument,
  presentFarmer,
  presentFpo,
  presentListing,
  presentMarket,
  presentMarketPrice,
  presentMessage,
  presentNotification,
  presentOffer,
  presentOrder,
  presentPayment,
  presentRequirement,
  presentReview,
  presentTransporter,
  presentUser,
} from '../../src/utils/presenters';

const id = '674a1b2c3d4e5f6789012345';

describe('presenters', () => {
  const presenters = [
    presentUser,
    presentFarmer,
    presentBuyer,
    presentMarket,
    presentCrop,
    presentListing,
    presentOffer,
    presentOrder,
    presentPayment,
    presentRequirement,
    presentFpo,
    presentTransporter,
    presentDelivery,
    presentMarketPrice,
    presentNotification,
    presentConversation,
    presentMessage,
    presentReview,
    presentDispute,
    presentDocument,
    presentAudit,
  ];

  it('renders sparse and populated documents', () => {
    const sparse = { _id: id };
    const populated = {
      toObject: () => ({
        _id: id,
        name: 'Rabi',
        phone: '9810000001',
        email: 'a@b.c',
        role: 'FARMER',
        roles: [id],
        password: 'hidden',
        farmerName: 'Rabi',
        businessName: 'Bapi',
        title: 'Tomato',
        quantity: 10,
        availableQuantity: 8,
        expectedPricePaise: 2800,
        minimumPricePaise: 2400,
        offeredPricePaise: 2600,
        unitPricePaise: 2800,
        subtotalPaise: 28000,
        commissionPaise: 0,
        transportChargePaise: 0,
        taxPaise: 0,
        discountPaise: 0,
        totalAmountPaise: 28000,
        amountPaise: 28000,
        refundedPaise: 0,
        targetPricePaise: 3000,
        minimumPricePaiseMarket: 1,
        orderNumber: 'VEG-2026-000001',
        orderId: id,
        buyerId: id,
        farmerId: id,
        cropId: id,
        marketId: id,
        listingId: id,
        userId: id,
        conversationId: id,
        senderId: id,
        reviewerId: id,
        revieweeId: id,
        uploadedBy: id,
        raisedBy: id,
        against: id,
        status: 'ACTIVE',
        isPhoneVerified: true,
        isEmailVerified: false,
        isActive: true,
        isBlocked: false,
        isDemo: true,
        isVerified: true,
        isNegotiable: false,
        allowBidding: true,
        location: { type: 'Point', coordinates: [88.48, 22.72] },
        bankDetails: { accountNumberMasked: '****7890' },
        participants: [id],
        images: [],
        vehicles: [],
        message: 'hello',
        rating: 5,
        fileName: 'pan.pdf',
        action: 'LOGIN',
        entity: 'User',
        entityId: id,
      }),
    };
    for (const present of presenters) {
      expect(present(sparse)).toEqual(expect.objectContaining({ _id: id }));
      expect(present(populated)).toEqual(expect.objectContaining({ _id: id }));
    }
    expect(presentFarmer(populated, { includePrivate: true }).phone).toBe('9810000001');
    expect(presentBuyer(populated, { includePrivate: false }).phone).toBeNull();
    expect(presentListing({ _id: id, farmerId: id, cropId: id, location: null }).location).toBeNull();
  });
});
